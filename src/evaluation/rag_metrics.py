"""
RAG evaluation metrics for question answering over scientific papers.
"""
import numpy as np
from typing import List, Dict, Tuple, Optional, Set
from dataclasses import dataclass
import re
from rouge_score import rouge_scorer
from nltk.translate.bleu_score import sentence_bleu, SmoothingFunction
import warnings

try:
    from bert_score import score as bert_score
    BERT_SCORE_AVAILABLE = True
except ImportError:
    BERT_SCORE_AVAILABLE = False


@dataclass
class RAGMetrics:
    """Container for RAG evaluation metrics."""
    # Answer quality metrics
    answer_relevance: float
    answer_accuracy: float
    answer_completeness: float
    answer_conciseness: float
    
    # Citation metrics
    citation_precision: float
    citation_recall: float
    citation_f1: float
    citation_accuracy: float
    
    # Faithfulness metrics
    faithfulness: float
    hallucination_rate: float
    
    # Text similarity metrics
    rouge_scores: Dict[str, float]
    bleu_score: float
    bert_score_f1: Optional[float]
    
    # Efficiency metrics
    retrieval_latency: float
    answer_latency: float
    tokens_per_answer: int


class RAGEvaluator:
    """
    Evaluator for RAG systems on scientific QA tasks.
    """
    
    def __init__(self, 
                 use_bert_score: bool = True,
                 rouge_types: List[str] = None):
        """
        Initialize RAG evaluator.
        
        Args:
            use_bert_score: Whether to use BERTScore (requires bert-score package)
            rouge_types: List of ROUGE types to calculate
        """
        if rouge_types is None:
            rouge_types = ["rouge1", "rouge2", "rougeL"]
        
        self.use_bert_score = use_bert_score and BERT_SCORE_AVAILABLE
        self.rouge_scorer = rouge_scorer.RougeScorer(rouge_types, use_stemmer=True)
        self.smoothing = SmoothingFunction().method1
    
    def evaluate_answer_quality(self, 
                               generated_answer: str,
                               reference_answer: str,
                               question: str = None) -> Dict[str, float]:
        """
        Evaluate answer quality against reference.
        
        Args:
            generated_answer: Answer generated by RAG system
            reference_answer: Ground truth/reference answer
            question: Original question (for relevance calculation)
            
        Returns:
            Dictionary of answer quality metrics
        """
        metrics = {}
        
        # ROUGE scores
        rouge_scores = self.rouge_scorer.score(reference_answer, generated_answer)
        for rouge_type in rouge_scores:
            metrics[f"{rouge_type}_precision"] = rouge_scores[rouge_type].precision
            metrics[f"{rouge_type}_recall"] = rouge_scores[rouge_type].recall
            metrics[f"{rouge_type}_f1"] = rouge_scores[rouge_type].fmeasure
        
        # BLEU score
        reference_tokens = reference_answer.split()
        generated_tokens = generated_answer.split()
        
        # Handle empty answers
        if not reference_tokens or not generated_tokens:
            metrics["bleu"] = 0.0
        else:
            try:
                bleu = sentence_bleu([reference_tokens], 
                                    generated_tokens,
                                    smoothing_function=self.smoothing)
                metrics["bleu"] = bleu
            except:
                metrics["bleu"] = 0.0
        
        # BERTScore if available
        if self.use_bert_score:
            try:
                P, R, F1 = bert_score([generated_answer], [reference_answer], 
                                      lang='en', verbose=False)
                metrics["bert_score_precision"] = float(P.mean())
                metrics["bert_score_recall"] = float(R.mean())
                metrics["bert_score_f1"] = float(F1.mean())
            except:
                metrics["bert_score_precision"] = 0.0
                metrics["bert_score_recall"] = 0.0
                metrics["bert_score_f1"] = 0.0
        
        # Answer length metrics
        metrics["answer_length"] = len(generated_answer.split())
        metrics["reference_length"] = len(reference_answer.split())
        metrics["length_ratio"] = metrics["answer_length"] / max(metrics["reference_length"], 1)
        
        # Conciseness (inverse of length ratio, clipped)
        metrics["conciseness"] = min(1.0, 1.0 / metrics["length_ratio"]) if metrics["length_ratio"] > 0 else 1.0
        
        # Calculate answer relevance if question is provided
        if question:
            relevance = self._calculate_answer_relevance(generated_answer, question)
            metrics["answer_relevance"] = relevance
        
        return metrics
    
    def evaluate_citations(self,
                          generated_answer: str,
                          cited_documents: List[Dict],
                          ground_truth_citations: List[str],
                          answer_span_to_doc_map: Dict[Tuple[int, int], str] = None) -> Dict[str, float]:
        """
        Evaluate citation accuracy and relevance.
        
        Args:
            generated_answer: Answer with citation markers
            cited_documents: List of cited documents with metadata
            ground_truth_citations: List of document IDs that should be cited
            answer_span_to_doc_map: Mapping from answer spans to document IDs
            
        Returns:
            Dictionary of citation metrics
        """
        metrics = {}
        
        # Extract citations from answer
        extracted_citations = self._extract_citations(generated_answer)
        
        # Convert to document IDs if possible
        citation_doc_ids = []
        for citation in extracted_citations:
            # Try to map citation marker to document ID
            doc_id = self._map_citation_to_doc(citation, cited_documents)
            if doc_id:
                citation_doc_ids.append(doc_id)
        
        # Calculate precision, recall, F1
        if ground_truth_citations:
            true_positives = len(set(citation_doc_ids) & set(ground_truth_citations))
            false_positives = len(set(citation_doc_ids) - set(ground_truth_citations))
            false_negatives = len(set(ground_truth_citations) - set(citation_doc_ids))
            
            precision = true_positives / max(len(citation_doc_ids), 1)
            recall = true_positives / max(len(ground_truth_citations), 1)
            f1 = 2 * precision * recall / max(precision + recall, 1e-10)
            
            metrics.update({
                "citation_precision": precision,
                "citation_recall": recall,
                "citation_f1": f1,
                "citation_count": len(citation_doc_ids),
                "ground_truth_citation_count": len(ground_truth_citations),
                "true_positives": true_positives,
                "false_positives": false_positives,
                "false_negatives": false_negatives,
            })
        
        # Calculate citation accuracy if we have span-to-doc mapping
        if answer_span_to_doc_map:
            accuracy = self._calculate_citation_accuracy(generated_answer, answer_span_to_doc_map)
            metrics["citation_accuracy"] = accuracy
        
        return metrics
    
    def evaluate_faithfulness(self,
                            generated_answer: str,
                            source_documents: List[Dict],
                            answer_span_to_doc_map: Dict[Tuple[int, int], str] = None) -> Dict[str, float]:
        """
        Evaluate faithfulness (factual accuracy) of generated answer.
        
        Args:
            generated_answer: Generated answer
            source_documents: Source documents used for generation
            answer_span_to_doc_map: Mapping from answer spans to document IDs
            
        Returns:
            Dictionary of faithfulness metrics
        """
        metrics = {}
        
        # Simple keyword-based faithfulness check
        # In practice, you'd want a more sophisticated approach
        # like using NLI models or fact-checking systems
        
        # Check for obvious contradictions
        contradiction_score = self._check_contradictions(generated_answer, source_documents)
        metrics["contradiction_score"] = contradiction_score
        
        # Estimate hallucination rate
        hallucination_rate = self._estimate_hallucination_rate(generated_answer, source_documents)
        metrics["hallucination_rate"] = hallucination_rate
        
        # Faithfulness score (1 - hallucination rate)
        metrics["faithfulness"] = 1.0 - hallucination_rate
        
        return metrics
    
    def evaluate_efficiency(self,
                          retrieval_times: List[float],
                          generation_times: List[float],
                          token_counts: List[int]) -> Dict[str, float]:
        """
        Evaluate efficiency metrics.
        
        Args:
            retrieval_times: List of retrieval latencies in seconds
            generation_times: List of generation latencies in seconds
            token_counts: List of token counts per answer
            
        Returns:
            Dictionary of efficiency metrics
        """
        metrics = {}
        
        if retrieval_times:
            metrics.update({
                "retrieval_latency_mean": np.mean(retrieval_times),
                "retrieval_latency_std": np.std(retrieval_times),
                "retrieval_latency_p95": np.percentile(retrieval_times, 95),
                "retrieval_latency_max": np.max(retrieval_times),
            })
        
        if generation_times:
            metrics.update({
                "generation_latency_mean": np.mean(generation_times),
                "generation_latency_std": np.std(generation_times),
                "generation_latency_p95": np.percentile(generation_times, 95),
                "generation_latency_max": np.max(generation_times),
            })
        
        if token_counts:
            metrics.update({
                "tokens_per_answer_mean": np.mean(token_counts),
                "tokens_per_answer_std": np.std(token_counts),
                "tokens_per_answer_max": np.max(token_counts),
            })
        
        return metrics
    
    def comprehensive_evaluate(self,
                             generated_answer: str,
                             reference_answer: str,
                             cited_documents: List[Dict],
                             ground_truth_citations: List[str],
                             source_documents: List[Dict],
                             question: str = None,
                             retrieval_time: float = None,
                             generation_time: float = None,
                             token_count: int = None) -> RAGMetrics:
        """
        Comprehensive evaluation of RAG output.
        
        Args:
            generated_answer: Generated answer from RAG system
            reference_answer: Ground truth answer
            cited_documents: Documents cited in answer
            ground_truth_citations: Documents that should be cited
            source_documents: Source documents used for generation
            question: Original question
            retrieval_time: Retrieval latency in seconds
            generation_time: Generation latency in seconds
            token_count: Number of tokens in generated answer
            
        Returns:
            RAGMetrics object with all evaluation results
        """
        # Evaluate answer quality
        answer_metrics = self.evaluate_answer_quality(generated_answer, reference_answer, question)
        
        # Evaluate citations
        citation_metrics = self.evaluate_citations(generated_answer, cited_documents, ground_truth_citations)
        
        # Evaluate faithfulness
        faithfulness_metrics = self.evaluate_faithfulness(generated_answer, source_documents)
        
        # Evaluate efficiency
        efficiency_metrics = {}
        if retrieval_time is not None and generation_time is not None and token_count is not None:
            efficiency_metrics = self.evaluate_efficiency([retrieval_time], [generation_time], [token_count])
        
        # Extract ROUGE scores
        rouge_scores = {}
        for key in answer_metrics:
            if key.startswith('rouge') and key.endswith('_f1'):
                rouge_name = key.replace('_f1', '')
                rouge_scores[rouge_name] = answer_metrics[key]
        
        return RAGMetrics(
            answer_relevance=answer_metrics.get('answer_relevance', 0.0),
            answer_accuracy=answer_metrics.get('rougeL_f1', 0.0),  # Using ROUGE-L as proxy
            answer_completeness=answer_metrics.get('rougeL_recall', 0.0),
            answer_conciseness=answer_metrics.get('conciseness', 0.0),
            citation_precision=citation_metrics.get('citation_precision', 0.0),
            citation_recall=citation_metrics.get('citation_recall', 0.0),
            citation_f1=citation_metrics.get('citation_f1', 0.0),
            citation_accuracy=citation_metrics.get('citation_accuracy', 0.0),
            faithfulness=faithfulness_metrics.get('faithfulness', 0.0),
            hallucination_rate=faithfulness_metrics.get('hallucination_rate', 0.0),
            rouge_scores=rouge_scores,
            bleu_score=answer_metrics.get('bleu', 0.0),
            bert_score_f1=answer_metrics.get('bert_score_f1', None),
            retrieval_latency=efficiency_metrics.get('retrieval_latency_mean', 0.0),
            answer_latency=efficiency_metrics.get('generation_latency_mean', 0.0),
            tokens_per_answer=int(efficiency_metrics.get('tokens_per_answer_mean', 0))
        )
    
    def _calculate_answer_relevance(self, answer: str, question: str) -> float:
        """Calculate relevance of answer to question."""
        # Simple word overlap based relevance
        question_words = set(question.lower().split())
        answer_words = set(answer.lower().split())
        
        if not question_words:
            return 0.0
        
        overlap = len(question_words & answer_words)
        relevance = overlap / len(question_words)
        
        return min(relevance, 1.0)
    
    def _extract_citations(self, text: str) -> List[str]:
        """Extract citation markers from text."""
        # Common citation patterns
        patterns = [
            r'\[(\d+)\]',  # [1], [2], etc.
            r'\((\d+)\)',  # (1), (2), etc.
            r'\[([A-Za-z]+ \d{4})\]',  # [Author Year]
            r'\(([A-Za-z]+ \d{4})\)',  # (Author Year)
        ]
        
        citations = []
        for pattern in patterns:
            matches = re.findall(pattern, text)
            citations.extend(matches)
        
        return list(set(citations))  # Remove duplicates
    
    def _map_citation_to_doc(self, citation: str, documents: List[Dict]) -> Optional[str]:
        """Map citation marker to document ID."""
        # Simple mapping: assume citations are indices into documents list
        if citation.isdigit():
            idx = int(citation) - 1  # Convert to 0-indexed
            if 0 <= idx < len(documents):
                return documents[idx].get('id', f"doc_{idx}")
        
        return None
    
    def _calculate_citation_accuracy(self, 
                                   answer: str, 
                                   span_to_doc_map: Dict[Tuple[int, int], str]) -> float:
        """Calculate accuracy of citations based on span-to-document mapping."""
        if not span_to_doc_map:
            return 0.0
        
        # This is a simplified implementation
        # In practice, you'd need to parse the answer and check each claim
        
        return 0.5  # Placeholder
    
    def _check_contradictions(self, answer: str, documents: List[Dict]) -> float:
        """Check for contradictions between answer and source documents."""
        # Simplified contradiction check
        # In practice, use NLI model or similar
        
        answer_lower = answer.lower()
        
        # Check for phrases that might indicate uncertainty/contradiction
        contradiction_phrases = [
            'contradict', 'contrary', 'opposite', 'disagree',
            'however', 'but', 'although', 'despite',
            'some say', 'others claim', 'debated', 'controversial'
        ]
        
        contradiction_count = sum(1 for phrase in contradiction_phrases 
                                 if phrase in answer_lower)
        
        # Normalize by answer length
        words = answer_lower.split()
        if len(words) > 0:
            contradiction_score = contradiction_count / len(words)
        else:
            contradiction_score = 0.0
        
        return min(contradiction_score, 1.0)
    
    def _estimate_hallucination_rate(self, answer: str, documents: List[Dict]) -> float:
        """Estimate hallucination rate in answer."""
        # Simplified estimation
        # In practice, use fact-checking or NLI models
        
        # Extract key entities/claims from answer
        answer_claims = self._extract_claims(answer)
        
        if not answer_claims:
            return 0.0
        
        # Check each claim against documents (simplified)
        supported_claims = 0
        for claim in answer_claims:
            if self._claim_in_documents(claim, documents):
                supported_claims += 1
        
        hallucination_rate = 1.0 - (supported_claims / len(answer_claims))
        return hallucination_rate
    
    def _extract_claims(self, text: str) -> List[str]:
        """Extract claims/statements from text."""
        # Simplified claim extraction
        sentences = re.split(r'[.!?]+', text)
        claims = [s.strip() for s in sentences if len(s.strip()) > 10]  # Filter short sentences
        
        return claims[:10]  # Limit to first 10 claims
    
    def _claim_in_documents(self, claim: str, documents: List[Dict]) -> bool:
        """Check if a claim is supported by any document."""
        claim_lower = claim.lower()
        
        for doc in documents:
            # Check in document text
            doc_text = doc.get('text', '').lower()
            if doc_text and claim_lower in doc_text:
                return True
            
            # Check in document summary/abstract
            doc_abstract = doc.get('abstract', '').lower()
            if doc_abstract and claim_lower in doc_abstract:
                return True
        
        return False


class ScientificRAGEvaluator(RAGEvaluator):
    """
    Specialized RAG evaluator for scientific papers.
    Adds metrics specific to scientific literature.
    """
    
    def evaluate_scientific_accuracy(self,
                                   generated_answer: str,
                                   reference_answer: str,
                                   domain: str = None) -> Dict[str, float]:
        """
        Evaluate scientific accuracy of generated answer.
        
        Args:
            generated_answer: Generated answer
            reference_answer: Reference/ground truth answer
            domain: Scientific domain (e.g., 'ml', 'physics', 'biology')
            
        Returns:
            Dictionary of scientific accuracy metrics
        """
        metrics = {}
        
        # Check for technical terminology accuracy
        tech_terms_accuracy = self._check_technical_terms(generated_answer, reference_answer)
        metrics["technical_terms_accuracy"] = tech_terms_accuracy
        
        # Check for mathematical notation/formula accuracy
        formula_accuracy = self._check_formulas(generated_answer, reference_answer)
        metrics["formula_accuracy"] = formula_accuracy
        
        # Check for citation format accuracy
        citation_format_accuracy = self._check_citation_format(generated_answer)
        metrics["citation_format_accuracy"] = citation_format_accuracy
        
        # Overall scientific accuracy (weighted average)
        weights = {
            'technical_terms': 0.4,
            'formulas': 0.3,
            'citation_format': 0.3
        }
        
        scientific_accuracy = (
            weights['technical_terms'] * tech_terms_accuracy +
            weights['formulas'] * formula_accuracy +
            weights['citation_format'] * citation_format_accuracy
        )
        
        metrics["scientific_accuracy"] = scientific_accuracy
        
        return metrics
    
    def _check_technical_terms(self, generated: str, reference: str) -> float:
        """Check accuracy of technical terminology."""
        # Extract technical terms (words with specific patterns)
        tech_patterns = [
            r'\b[A-Z]{2,}\b',  # Acronyms like CNN, GPT, BERT
            r'\b[a-z]+-[a-z]+\b',  # Hyphenated terms
            r'\b\d+D\b',  # 2D, 3D, etc.
        ]
        
        ref_terms = set()
        gen_terms = set()
        
        for pattern in tech_patterns:
            ref_terms.update(re.findall(pattern, reference))
            gen_terms.update(re.findall(pattern, generated))
        
        if not ref_terms:
            return 1.0  # No technical terms to check
        
        # Calculate precision of technical terms
        correct_terms = ref_terms & gen_terms
        if gen_terms:
            precision = len(correct_terms) / len(gen_terms)
        else:
            precision = 0.0
        
        # Calculate recall of technical terms
        recall = len(correct_terms) / len(ref_terms)
        
        # F1 score
        if precision + recall > 0:
            f1 = 2 * precision * recall / (precision + recall)
        else:
            f1 = 0.0
        
        return f1
    
    def _check_formulas(self, generated: str, reference: str) -> float:
        """Check accuracy of mathematical formulas."""
        # Extract formulas (simplified pattern matching)
        formula_patterns = [
            r'\$[^$]+\$',  # LaTeX inline math
            r'\\\[.*?\\\]',  # LaTeX display math
            r'\\\(.*?\\\)',  # LaTeX inline math (alternative)
        ]
        
        ref_formulas = []
        gen_formulas = []
        
        for pattern in formula_patterns:
            ref_formulas.extend(re.findall(pattern, reference))
            gen_formulas.extend(re.findall(pattern, generated))
        
        if not ref_formulas:
            return 1.0  # No formulas to check
        
        # Simple formula matching (could be more sophisticated)
        matched = 0
        for gen_formula in gen_formulas:
            for ref_formula in ref_formulas:
                # Simplified matching: check if formulas are similar
                if self._formulas_similar(gen_formula, ref_formula):
                    matched += 1
                    break
        
        accuracy = matched / max(len(ref_formulas), 1)
        return accuracy
    
    def _formulas_similar(self, formula1: str, formula2: str) -> bool:
        """Check if two formulas are similar."""
        # Remove whitespace and common formatting
        clean1 = re.sub(r'\s+', '', formula1)
        clean2 = re.sub(r'\s+', '', formula2)
        
        # Check for significant overlap
        # This is a simplified approach
        min_len = min(len(clean1), len(clean2))
        if min_len == 0:
            return False
        
        # Calculate character-level similarity
        matches = sum(1 for c1, c2 in zip(clean1, clean2) if c1 == c2)
        similarity = matches / max(len(clean1), len(clean2))
        
        return similarity > 0.7  # 70% similarity threshold
    
    def _check_citation_format(self, text: str) -> float:
        """Check if citations follow proper scientific format."""
        # Check for various citation formats
        formats = [
            (r'\[\d+\]', 1.0),  # Numbered citations [1]
            (r'\([A-Z][a-z]+ et al\. \d{4}\)', 1.0),  # Author-year (Smith et al. 2020)
            (r'\([A-Z][a-z]+ \d{4}\)', 1.0),  # Single author (Smith 2020)
            (r'\d+', 0.5),  # Just numbers (less formal)
        ]
        
        citations = self._extract_citations(text)
        if not citations:
            return 1.0  # No citations is technically correct
        
        format_scores = []
        for citation in citations:
            best_score = 0.0
            for pattern, score in formats:
                if re.fullmatch(pattern, citation):
                    best_score = max(best_score, score)
                    break
            format_scores.append(best_score)
        
        return np.mean(format_scores) if format_scores else 0.0